-- Run once in Supabase SQL Editor to enable the loyalty rewards program.
-- Every completed appointment earns 10 points. Redeem 50 points for a EUR 5 salon voucher.

create table if not exists public.loyalty_ledger (
    id bigint generated by default as identity primary key,
    customer_id uuid not null references public.profiles(id) on delete cascade,
    appointment_id bigint references public.appointments(id) on delete set null,
    points integer not null check (points <> 0),
    entry_type text not null check (entry_type in ('visit_earned', 'voucher_redeemed')),
    created_at timestamptz not null default now()
);

create unique index if not exists loyalty_ledger_one_visit_award
    on public.loyalty_ledger (appointment_id)
    where appointment_id is not null;

create table if not exists public.loyalty_vouchers (
    code text primary key,
    customer_id uuid not null references public.profiles(id) on delete cascade,
    points_cost integer not null default 50 check (points_cost = 50),
    status text not null default 'Available' check (status in ('Available', 'Redeemed')),
    created_at timestamptz not null default now(),
    redeemed_at timestamptz,
    redeemed_by uuid references public.profiles(id) on delete set null
);

alter table public.loyalty_ledger enable row level security;
alter table public.loyalty_vouchers enable row level security;

revoke all on public.loyalty_ledger, public.loyalty_vouchers from anon, authenticated;
grant select on public.loyalty_ledger, public.loyalty_vouchers to authenticated;

drop policy if exists "Customers read their loyalty ledger" on public.loyalty_ledger;
create policy "Customers read their loyalty ledger"
    on public.loyalty_ledger for select to authenticated
    using (customer_id = (select auth.uid()));

drop policy if exists "Admins read all loyalty ledger" on public.loyalty_ledger;
create policy "Admins read all loyalty ledger"
    on public.loyalty_ledger for select to authenticated
    using (public.is_admin());

drop policy if exists "Customers read their loyalty vouchers" on public.loyalty_vouchers;
create policy "Customers read their loyalty vouchers"
    on public.loyalty_vouchers for select to authenticated
    using (customer_id = (select auth.uid()));

drop policy if exists "Admins read all loyalty vouchers" on public.loyalty_vouchers;
create policy "Admins read all loyalty vouchers"
    on public.loyalty_vouchers for select to authenticated
    using (public.is_admin());

create or replace function public.award_completed_visit_points()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
    v_should_award boolean := false;
begin
    if new.status = 'Completed' then
        if tg_op = 'INSERT' then
            v_should_award := true;
        elsif old.status is distinct from new.status then
            v_should_award := true;
        end if;
    end if;

    if v_should_award then
        insert into public.loyalty_ledger (customer_id, appointment_id, points, entry_type)
        values (new.customer_id, new.id, 10, 'visit_earned')
        on conflict (appointment_id) where appointment_id is not null do nothing;
    end if;
    return new;
end;
$function$;

drop trigger if exists award_completed_visit_points on public.appointments;
create trigger award_completed_visit_points
    after insert or update on public.appointments
    for each row execute function public.award_completed_visit_points();

-- Award points for appointments that were already completed before this setup.
insert into public.loyalty_ledger (customer_id, appointment_id, points, entry_type)
select customer_id, id, 10, 'visit_earned'
from public.appointments
where status = 'Completed'
on conflict (appointment_id) where appointment_id is not null do nothing;

create or replace function public.customer_redeem_loyalty_voucher()
returns text
language plpgsql
security definer
set search_path = ''
as $function$
declare
    v_customer_id uuid := auth.uid();
    v_balance integer;
    v_code text;
begin
    if v_customer_id is null then
        raise exception 'Sign in to redeem a reward.' using errcode = '28000';
    end if;

    perform 1 from public.profiles where id = v_customer_id for update;
    if not found then
        raise exception 'Customer profile not found.' using errcode = 'P0002';
    end if;

    select coalesce(sum(points), 0)::integer
      into v_balance
      from public.loyalty_ledger
     where customer_id = v_customer_id;

    if v_balance < 50 then
        raise exception 'You need 50 points to redeem a voucher.' using errcode = '22023';
    end if;

    v_code := 'GLOW-' || upper(substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 8));
    insert into public.loyalty_vouchers (code, customer_id)
    values (v_code, v_customer_id);

    insert into public.loyalty_ledger (customer_id, points, entry_type)
    values (v_customer_id, -50, 'voucher_redeemed');

    return v_code;
end;
$function$;

create or replace function public.admin_redeem_loyalty_voucher(p_voucher_code text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
begin
    if not public.is_admin() then
        raise exception 'Administrator access required.' using errcode = '42501';
    end if;

    update public.loyalty_vouchers
       set status = 'Redeemed',
           redeemed_at = now(),
           redeemed_by = auth.uid()
     where code = upper(trim(p_voucher_code))
       and status = 'Available';

    if not found then
        raise exception 'Voucher not found or already redeemed.' using errcode = 'P0002';
    end if;

    return true;
end;
$function$;

revoke all on function public.award_completed_visit_points() from public, anon, authenticated;
revoke all on function public.customer_redeem_loyalty_voucher() from public, anon;
revoke all on function public.admin_redeem_loyalty_voucher(text) from public, anon;
grant execute on function public.customer_redeem_loyalty_voucher() to authenticated;
grant execute on function public.admin_redeem_loyalty_voucher(text) to authenticated;
